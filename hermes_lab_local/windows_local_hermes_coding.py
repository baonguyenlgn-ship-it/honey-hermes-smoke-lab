"""Real local-only Hermes Windows inference -> QA -> bounded model repair.

This is NOT a signed Codespace / Nous Gate B run, and it never publishes
generated bytes or issues new GitHub work. A genuine model response is
required on every attempt. No fake inference, no hardcoded generated result.
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

from hermes_lab_local.codespaces_stream_gate import terminal_source
from hermes_lab_local.gateway_failure_evidence import diagnose

MAX_REPAIRS = 2
PINNED_HERMES = "bf0203a794a07aac3ff764972ab9087baa4e4f4e"
EXPECTED = "def normalize_sku(value):\n    return str(value).strip().upper().replace(' ', '-')"
TESTS = (
    (" ab 12 ", "AB-12"), ("xoài cát chu", "XOÀI-CÁT-CHU"),
    (" a  b ", "A--B"), (" 안 녕 ", "안-녕"),
    ("  ", ""), (123, "123"), (None, "NONE"),
)

class QaRejected(ValueError):
    pass

def qa_original_source(source: str) -> bytes:
    if not isinstance(source, str):
        raise QaRejected("NON_TEXT_SOURCE")
    raw = source.encode("utf-8")
    if not (40 <= len(raw) <= 2048) or any(x in source for x in ("\\x00", "\\r", "\\ufeff")):
        raise QaRejected("UNSAFE_OR_OUT_OF_BOUNDS")
    try:
        tree = ast.parse(source)
    except (ValueError, SyntaxError):
        raise QaRejected("NOT_PARSEABLE_PYTHON") from None
    if ast.dump(tree, include_attributes=False) != ast.dump(
        ast.parse(EXPECTED), include_attributes=False
    ):
        raise QaRejected("AST_NOT_ALLOWLISTED")
    scope = {"__builtins__": {"str": str}}
    exec(compile(tree, "<inert-local-model-qa>", "exec"), scope)
    for arg, expected in TESTS:
        if scope["normalize_sku"](arg) != expected:
            raise QaRejected("INDEPENDENT_BEHAVIOR_REJECTED")
    return raw

def emit_gateway_diagnostics(result, env):
    """Only redacted booleans/types, never raw gateway stdout/stderr or secrets."""
    import re
    stdout = result.stdout[:65536].decode("utf-8", errors="replace")
    stderr = result.stderr[:65536].decode("utf-8", errors="replace")
    records = []
    for line in stdout.splitlines()[:512]:
        try:
            event = json.loads(line)
        except (ValueError, TypeError):
            continue
        if isinstance(event, dict) and isinstance(event.get("type"), str):
            records.append(event)
    terminal = [e for e in records if e.get("type") == "result"]
    print("HERMES_DIAG_CLI_EXIT_NONZERO=" + str(result.returncode != 0))
    print("HERMES_DIAG_STDOUT_BYTES=" + str(len(result.stdout)))
    print("HERMES_DIAG_STDERR_BYTES=" + str(len(result.stderr)))
    print("HERMES_DIAG_EVENT_COUNT=" + str(len(records)))
    print("HERMES_DIAG_LAST_EVENT_TYPE=" + str(records[-1].get("type") if records else "NONE"))
    print("HERMES_DIAG_TERMINAL_COUNT=" + str(len(terminal)))
    if terminal:
        last = terminal[-1]
        print("HERMES_DIAG_TERMINAL_EXIT_NONZERO=" + str(last.get("exit_code") != 0))
        print("HERMES_DIAG_TERMINAL_ERROR_PRESENT=" + str(bool(last.get("error"))))
        print("HERMES_DIAG_TERMINAL_ERROR_CLASS=" +
              diagnose(str(last.get("error") or ""))["classification"])
    print("HERMES_DIAG_STDERR_CLASS=" + diagnose(stderr)["classification"])
    home = env.get("HERMES_HOME")
    if not home:
        print("HERMES_DIAG_GATEWAY_LOG_PRESENT=False")
        return
    for name in ("gateway.log", "errors.log"):
        log_path = Path(home) / "logs" / name
        try:
            raw = log_path.read_bytes()
            sample = raw[-65536:].decode("utf-8", errors="replace")
        except OSError:
            print("HERMES_DIAG_" + name.replace(".", "_").upper() + "_PRESENT=False")
            continue
        label = "HERMES_DIAG_" + name.replace(".", "_").upper()
        print(label + "_PRESENT=True")
        print(label + "_CLASS=" + diagnose(sample)["classification"])
        print(label + "_ERROR_LINE_COUNT=" +
              str(sum(bool(re.search(r"(?i)error|exception|fail|refused|denied",
                                     line)) for line in sample.splitlines())))
        print(label + "_HTTP_401=" + str(bool(re.search(r"(?i)\\b401\\b", sample))))
        print(label + "_HTTP_400=" + str(bool(re.search(r"(?i)\\b400\\b", sample))))
        print(label + "_PROVIDER_CUSTOM=" +
              str(bool(re.search(r"(?i)provider.{0,40}custom", sample))))
        print(label + "_MODEL_LOCAL=" +
              str(bool(re.search(r"(?i)local-qwen|127\\.0\\.0\\.1:18081", sample))))


def model_turn(prompt: str, attempt: int, *, source: Path, temp: Path) -> str:
    prompt_path = temp / f"request-{attempt}.txt"
    prompt_path.write_text(prompt, encoding="utf-8")
    executable = os.environ.get("HERMES_PYTHON", "python")
    env = os.environ.copy()
    for key in (
        "GITHUB_TOKEN", "GH_TOKEN", "GITHUB_PAT", "NOUS_API_KEY",
        "OPENAI_API_KEY", "ANTHROPIC_API_KEY", "OPENROUTER_API_KEY",
    ):
        env.pop(key, None)
    cmd = [
        executable, str(source / "hermes"), "chat",
        "--query-file", str(prompt_path), "--oneshot",
        "--format", "stream-json", "--max-turns", "1",
    ]
    try:
        result = subprocess.run(cmd, cwd=source, env=env,
                                capture_output=True, timeout=115, check=False)
    except (OSError, subprocess.TimeoutExpired):
        raise RuntimeError("HERMES_MODEL_OUTCOME_UNKNOWN_NO_RETRY") from None
    if result.returncode or len(result.stdout) > 65536 or len(result.stderr) > 65536:
        # Classify existing diagnostic text without exposing response bodies,
        # API fields, model messages or the private stderr.
        reason = diagnose(result.stderr.decode("utf-8", errors="replace"))
        print("HERMES_LOCAL_GATEWAY_FAILURE_CLASS=" + reason["classification"])
        emit_gateway_diagnostics(result, env)
        raise RuntimeError("HERMES_CLI_PROVIDER_OR_PROTOCOL_FAILED_NO_RETRY")
    try:
        response = terminal_source(result.stdout.decode("utf-8", "strict"))
    except (UnicodeError, ValueError, json.JSONDecodeError):
        raise RuntimeError("HERMES_TERMINAL_RESPONSE_NOT_PROVEN_NO_RETRY") from None
    return response

def main() -> None:
    src = Path(os.environ["HERMES_UPSTREAM_SOURCE"]).resolve()
    tmp = Path(os.environ["RUNNER_TEMP"]).resolve() / "hermes-local-original"
    tmp.mkdir(mode=0o700, exist_ok=False)
    if not (src / ".git").is_dir():
        raise RuntimeError("SOURCE_GIT_NOT_PRESENT")
    actual = subprocess.check_output(
        ["git", "-C", str(src), "rev-parse", "HEAD"], text=True
    ).strip()
    if actual != PINNED_HERMES:
        raise RuntimeError("HERMES_UPSTREAM_SHA_NOT_PINNED")
    prompt = (
        "Write ONLY valid raw Python source, no markdown, to define exactly "
        "one function named normalize_sku(value). It must convert any input "
        "to str, remove leading and trailing whitespace, uppercase Unicode, "
        "and replace each ASCII space with one hyphen. "
        "No imports, comments, external calls, tools or other functions."
    )
    report = []
    for attempt in range(MAX_REPAIRS + 1):
        print(f"HERMES_NATIVE_WINDOWS_REAL_MODEL_TURN_ATTEMPT={attempt+1}", flush=True)
        response = model_turn(prompt, attempt, source=src, temp=tmp)
        try:
            approved = qa_original_source(response)
        except QaRejected as error:
            code = str(error)
            report.append({"attempt": attempt+1, "status": "QA_REJECTED",
                           "reason": code})
            print("HERMES_NATIVE_WINDOWS_INDEPENDENT_QA_REJECTED=" + code, flush=True)
            if attempt == MAX_REPAIRS:
                raise RuntimeError("HERMES_REAL_MODEL_REPAIR_BUDGET_EXHAUSTED")
            prompt = (
                "Independent AST and behavioral QA rejected your previous "
                f"Python code with code {code}. Try again. Output ONLY "
                "Python source: one def normalize_sku(value), with return "
                "str(value).strip().upper().replace(' ', '-'). "
                "No Markdown, imports, comments, tools or extra code."
            )
            continue
        sha = hashlib.sha256(approved).hexdigest()
        report.append({"attempt": attempt+1, "status": "QA_PASS",
                       "sha256": sha})
        # Model-authored code stays only in transient runner storage.
        # Output only a SHA and bounded evidence, never claim provider custody.
        print(json.dumps({
            "status": "ACTUAL_LOCAL_HERMES_MODEL_CODE_QA_PASS",
            "sha256": sha, "bytes": len(approved), "attempts": attempt+1,
            "repairs": attempt, "new_task": "normalize_sku",
            "provider": "loopback-local-gguf-not-nous",
            "source_origin_signed": False,
            "gate_b_live_signed": False,
            "automatic_next_mission_proven": False,
        }, sort_keys=True), flush=True)
        return
    raise RuntimeError("UNREACHABLE_REPAIR_STATE")

if __name__ == "__main__":
    main()
